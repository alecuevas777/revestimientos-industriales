function atDay(daysAgo: number, hour: number, minute: number) {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  date.setHours(hour, minute, 0, 0);
  return date.toISOString();
}

function minutesAgo(minutes: number) {
  return new Date(Date.now() - minutes * 60 * 1000).toISOString();
}

function sector(
  input: Omit<SurveySector, 'createdAt' | 'updatedAt' | 'uses' | 'exposures' | 'elements' | 'photos'> & {
    at: string;
    uses?: SurveySector['uses'];
    exposures?: SurveySector['exposures'];
    elements?: SurveyElement[];
    photos?: PhotoEvidence[];
  },
): SurveySector {
  const { at, ...rest } = input;
  return {
    uses: [],
    exposures: [],
    elements: [],
    photos: [],
    ...rest,
    createdAt: at,
    updatedAt: at,
  };
}

function photos(
  surveyId: string,
  ownerId: string,
  count: number,
  at: string,
  category: PhotoCategory = 'detail',
  extra?: Partial<PhotoEvidence>,
): PhotoEvidence[] {
  return Array.from({ length: count }, (_, index) => ({
    id: `pho_${ownerId}_${index + 1}`,
    uri: '',
    surveyId,
    category: index === 0 ? 'overview' : category,
    caption:
      index === 0
        ? 'Vista general al momento de la inspección.'
        : 'Detalle del hallazgo registrado en terreno.',
    createdAt: at,
    ...extra,
  }));
}

function element(input: Omit<SurveyElement, 'createdAt' | 'updatedAt' | 'problems' | 'exposures' | 'photos'> & {
  at: string;
  problems?: SurveyElement['problems'];
  exposures?: SurveyElement['exposures'];
  photos?: PhotoEvidence[];
}): SurveyElement {
  const { at, ...rest } = input;
  return {
    problems: [],
    exposures: [],
    photos: [],
    ...rest,
    createdAt: at,
    updatedAt: at,
  };
}

