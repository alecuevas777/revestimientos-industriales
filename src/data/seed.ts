function atDay(daysAgo: number, hour: number, minute: number) {
  const date = new Date();
  date.setDate(date.getDate() - daysAgo);
  date.setHours(hour, minute, 0, 0);
  return date.toISOString();
}

function minutesAgo(minutes: number) {
  return new Date(Date.now() - minutes * 60 * 1000).toISOString();
}

function sector(input: Omit<SurveySector, 'createdAt' | 'updatedAt' | 'contaminations' | 'uses' | 'exposures'> & {
  at: string;
  contaminations?: SurveySector['contaminations'];
  uses?: SurveySector['uses'];
  exposures?: SurveySector['exposures'];
}): SurveySector {
  const { at, ...rest } = input;
  return {
    contaminations: [],
    uses: [],
    exposures: [],
    ...rest,
    createdAt: at,
    updatedAt: at,
  };
}

function photos(
  surveyId: string,
  sectorId: string | undefined,
  count: number,
  at: string,
  category: PhotoCategory = 'problem',
): PhotoEvidence[] {
  return Array.from({ length: count }, (_, index) => ({
    id: `pho_${sectorId ?? surveyId}_${index + 1}`,
    uri: '',
    surveyId,
    sectorId,
    category: index === 0 ? 'overview' : category,
    caption:
      index === 0
        ? 'Vista general del sector al momento de la inspección.'
        : 'Detalle del hallazgo registrado en terreno.',
    createdAt: at,
  }));
}

